"""
The Python engine against the TypeScript engine, on identical fixed inputs.

tests/fixtures/parity.json holds the inputs and the TypeScript engine's
exact results (generated by lib/backtest/parity.test.ts). Each case is run
through the same path the API uses (the request models, then the engine).

Tolerances:
- Dates, sides, symbols, trade counts: exactly equal.
- Every number (equity values, shares, fill prices, metrics): equal within a
  relative 1e-9 (absolute 1e-9 near zero). Both engines do the same IEEE-754
  double arithmetic in the same order, so in practice they agree to the last
  digit or within a few units of it; the tolerance leaves room for math
  libraries that round pow() and sqrt() differently.
"""

from __future__ import annotations

import json
import math
from pathlib import Path

import pytest

from analytics import api, engine

FIXTURES = json.loads((Path(__file__).parent / "fixtures" / "parity.json").read_text())["cases"]
REL = 1e-9
ABS = 1e-9


def close(a: float | None, b: float | None) -> bool:
    if a is None or b is None:
        return a is b
    return math.isclose(a, b, rel_tol=REL, abs_tol=ABS)


def run_case(case: dict) -> api.BacktestResponse:
    request = api.BacktestRequest.model_validate(case["request"])
    return api.run_backtest(request)


def compare_run(actual: api.RunModel, expected: dict, label: str) -> float:
    """Asserts one run matches; returns the largest relative difference seen."""
    worst = 0.0

    def check(a, b, what):
        nonlocal worst
        assert close(a, b), f"{label} {what}: python {a!r} vs typescript {b!r}"
        if a is not None and b not in (None, 0):
            worst = max(worst, abs(a - b) / abs(b))

    assert [p.time for p in actual.equity] == [p["time"] for p in expected["equity"]], f"{label}: different days"
    for p, q in zip(actual.equity, expected["equity"]):
        check(p.price, q["price"], f"equity on {q['time']}")

    assert len(actual.trades) == len(expected["trades"]), f"{label}: {len(actual.trades)} trades vs {len(expected['trades'])}"
    for t, u in zip(actual.trades, expected["trades"]):
        assert (t.time, t.symbol, t.side) == (u["time"], u["symbol"], u["side"]), f"{label}: trade {t} vs {u}"
        check(t.shares, u["shares"], "trade shares")
        check(t.price, u["price"], "fill price")
        check(t.commission, u["commission"], "commission")

    m = actual.metrics.model_dump(by_alias=True)
    for key, value in expected["metrics"].items():
        if key in ("trades", "drawdownPeak", "drawdownTrough"):
            assert m[key] == value, f"{label} {key}: {m[key]} vs {value}"
        else:
            check(m[key], value, key)
    return worst


@pytest.mark.parametrize("case", FIXTURES, ids=[c["name"] for c in FIXTURES])
def test_matches_typescript(case):
    result = run_case(case)
    worst = max(compare_run(result.run, case["expected"]["run"], "strategy"), compare_run(result.benchmark, case["expected"]["benchmark"], "benchmark"))
    # Recorded for the docs: how close the engines actually are.
    print(f"{case['name']}: largest relative difference {worst:.2e}")


def test_fixtures_cover_the_edge_cases():
    names = {c["name"] for c in FIXTURES}
    assert {"missing-dates-two-stocks", "warm-up-longer-than-data", "commission-larger-than-cash", "sawtooth-whipsaw"} <= names


def test_warm_up_longer_than_the_data_is_explained():
    case = next(c for c in FIXTURES if c["name"] == "warm-up-longer-than-data")
    assert run_case(case).warnings and "never traded" in run_case(case).warnings[0]
